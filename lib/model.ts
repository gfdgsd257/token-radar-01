// The token radar's model, radar-2: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds
// pre-token protocols below the watchlist floor: the early rows the radar exists to find. A protocol is
// pre-token when its index entry records no token (no market cap, no CoinGecko id, no symbol); the
// snapshot's live-token protocols are kept apart and shown as the market's own values, never mixed into
// the ranked board.
//
// What counts as rankable follows the watchlist's own definition, not a looser one: a protocol is out
// when it is an exchange, a versioned pool of another protocol, a bridge or canonical bridge, a liquid
// staking / liquid restaking / restaked-BTC product, or its name carries a whole word wrapped, staked
// or staking or begins with an exchange's name. Those are products of tokens that already trade —
// WBTC is Bitcoin on Ethereum, a staked SOL receipt is SOL in a staking product — and ranking them as
// launches that have not happened yet would be wrong. Every watchlist slug passes this test.
//
// Implied value follows only from the snapshot's own figures, in three factors:
//
//   category multiple = the live market's own ratio for the protocol's category:
//     raw(cat)  = median(mcap_usd / tvl_usd) over the snapshot's live-token protocols in that
//                 category with a TVL above zero and a market cap on record
//     multiple  = clamp((n x raw(cat) + 10 x global) / (n + 10), 0.05, 0.80)
//     global    = median(mcap_usd / tvl_usd) over every live-token protocol in the snapshot
//     A category with no live protocol takes the global median. The multiple is a market ratio the
//     snapshot itself carries, not a constant: lending's live tokens trade near 0.15x TVL, DEXs near
//     0.26x, and a category with one live token is shrunk nine-tenths of the way to the global
//     median, so one outlier cannot set it.
//
//   growth   = clamp(change_7d, -50, 100) per cent; growthMult = 1 + (growth / 100) x 0.6
//   age      = days since first listing (unknown: 365); ageMult rises 0.70 -> 1.00 over two years
//              of running with no token, then eases back to 0.85 for protocols that have run more
//              than three years with no token, because a launch that has not come in five years is
//              less likely to come soon than one that has not come in two.
//
//   implied  = max(1, round(tvl_usd x categoryMultiple x growthMult x ageMult))
//
// No protocol name is ever special-cased: the same function scores every row.

